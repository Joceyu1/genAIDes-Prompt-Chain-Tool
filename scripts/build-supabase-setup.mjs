#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildApplyQuery, readMigrations } from "./configure-supabase.mjs";

export async function renderSetupSQL() {
  return `-- Generated by: node scripts/build-supabase-setup.mjs
-- Legacy initial-schema reference; NOT compatible with the current assignment-schema app.
-- For the linked project use install-existing-chain-admin.sql instead.
-- Preserves profile rows and existing policies. Grants no user a new role.
-- Unknown app objects or incompatible profiles abort the entire transaction.
-- Do not rerun this initial setup after it succeeds; use versioned migrations.
${buildApplyQuery(await readMigrations())}\n`;
}

export async function renderRepairSQL() {
  const migration = await readFile(
    new URL(
      "../supabase/migrations/20261104000000_chainlab_superadmin_check.sql",
      import.meta.url,
    ),
    "utf8",
  );
  const declaration =
    "create or replace function public.chainlab_is_superadmin()";
  if (!migration.includes(declaration))
    throw new Error(
      "The RPC declaration changed. Review the repair generator.",
    );
  const guard = `do $guard$ begin
 if exists (
  select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and p.proname='chainlab_is_superadmin'
 ) then
  raise exception 'chainlab_is_superadmin already exists; repair aborted without replacing it';
 end if;
end $guard$;`;
  return `-- Generated by: node scripts/build-supabase-setup.mjs --repair
-- Adds only the no-argument authorization RPC to an existing shared project.
-- Does not create, adopt, or alter chain tables, profile policies, or user data.
${migration.replace(/^begin;\s*$/m, `begin;\n\n${guard}`).replace(declaration, "create function public.chainlab_is_superadmin()")}`;
}

export const EXISTING_MIGRATION_FILES = [
  "20261104020000_existing_chain_admin.sql",
  "20261104025000_chainlab_model_registry.sql",
  "20261104030000_chainlab_history.sql",
  "20261104040000_chainlab_legacy_history.sql",
];

export async function renderGeminiUpgradeSQL() {
  const migration = await readFile(
    new URL(
      "../supabase/migrations/20261107000000_gemini_fallback_models.sql",
      import.meta.url,
    ),
    "utf8",
  );
  return `-- Generated by: node scripts/build-supabase-setup.mjs --gemini\n${migration}`;
}

function stripTransaction(source) {
  if (
    (source.match(/^begin;\s*$/gm) || []).length !== 1 ||
    (source.match(/^commit;\s*$/gm) || []).length !== 1
  )
    throw new Error(
      "Existing-schema migration transaction format changed. Review the generator.",
    );
  return source.replace(/^begin;\s*$/m, "").replace(/^commit;\s*$/m, "");
}

export async function renderExistingSQL() {
  const authorization = await readFile(
    new URL(
      "../supabase/migrations/20261104000000_chainlab_superadmin_check.sql",
      import.meta.url,
    ),
    "utf8",
  );
  const declaration = authorization.match(
    /create or replace function public\.chainlab_is_superadmin\(\)[\s\S]*?\$\$;/,
  )?.[0];
  const body = declaration?.match(/\bas\s+\$\$([\s\S]*?)\$\$;/)?.[1];
  if (!declaration || !body)
    throw new Error(
      "The authorization function format changed. Review the generator.",
    );
  const expectedBody = body
    .toLowerCase()
    .replace(/\s+/g, "")
    .replaceAll("'", "''");
  const createFunction = declaration.replace(
    "create or replace function",
    "create function",
  );
  const migrations = await Promise.all(
    EXISTING_MIGRATION_FILES.map((name) =>
      readFile(
        new URL(`../supabase/migrations/${name}`, import.meta.url),
        "utf8",
      ),
    ),
  );
  const bootstrap = `do $auth_guard$
declare v_count integer;v_function record;v_owner_safe boolean;
begin
  if to_regclass('public.profiles') is null then
    raise exception 'The existing profiles table is required';
  end if;
  select count(*) into v_count from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and p.proname='chainlab_is_superadmin';
  if v_count=0 then
    execute $chainlab_definition$
${createFunction}
$chainlab_definition$;
  elsif v_count<>1 then
    raise exception 'Unknown chainlab_is_superadmin overloads exist; installation aborted without replacing them';
  end if;
  select p.* into v_function from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and p.proname='chainlab_is_superadmin';
  if v_function.prokind<>'f' or v_function.pronargs<>0 or v_function.proretset
     or v_function.prorettype<>'boolean'::regtype
     or v_function.prolang<>(select oid from pg_language where lanname='sql')
     or not v_function.prosecdef or v_function.provolatile<>'s'
     or v_function.proconfig is distinct from array['search_path=""']::text[]
     or regexp_replace(lower(v_function.prosrc),'[[:space:]]','','g')<>'${expectedBody}' then
    raise exception 'Unknown chainlab_is_superadmin definition exists; installation aborted without replacing it';
  end if;
  select r.rolname='postgres' or r.rolsuper or r.rolbypassrls
    or (r.oid=c.relowner and not c.relforcerowsecurity)
  into v_owner_safe from pg_roles r cross join pg_class c
  where r.oid=v_function.proowner and c.oid='public.profiles'::regclass;
  if v_owner_safe is not true then
    raise exception 'The authorization function owner cannot safely inspect the existing role flag; installation aborted';
  end if;
end;
$auth_guard$;
revoke all on function public.chainlab_is_superadmin() from public,anon;
grant execute on function public.chainlab_is_superadmin() to authenticated;`;
  return `-- Generated by: node scripts/build-supabase-setup.mjs --existing
-- One transaction installs authorization plus existing assignment-schema administration.
-- Missing authorization is created from the reviewed migration; existing definitions
-- must match exactly after whitespace/case normalization and are never replaced.
-- Leaves existing chain constraints, profile policies, model UUIDs and data intact.
begin;
${bootstrap}
${migrations.map(stripTransaction).join("\n\n")}
commit;\n`;
}

async function main() {
  const args = process.argv.slice(2);
  if (
    args.some(
      (arg) => !["--check", "--repair", "--existing", "--gemini"].includes(arg),
    ) ||
    new Set(args).size !== args.length ||
    args.filter((arg) => ["--repair", "--existing", "--gemini"].includes(arg))
      .length > 1
  )
    throw new Error(
      "Usage: node scripts/build-supabase-setup.mjs [--repair | --existing | --gemini] [--check]",
    );
  const name = args.includes("--gemini")
    ? "supabase/enable-gemini.sql"
    : args.includes("--existing")
      ? "supabase/install-existing-chain-admin.sql"
      : args.includes("--repair")
        ? "supabase/repair-superadmin-access.sql"
        : "supabase/setup.sql";
  const destination = new URL(`../${name}`, import.meta.url);
  const output = args.includes("--gemini")
    ? await renderGeminiUpgradeSQL()
    : args.includes("--existing")
      ? await renderExistingSQL()
      : args.includes("--repair")
        ? await renderRepairSQL()
        : await renderSetupSQL();
  if (args.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== output)
      throw new Error(`${name} is stale. Regenerate it with this script.`);
    console.log(`${name} matches its reviewed migration source and guards.`);
  } else {
    await writeFile(destination, output);
    console.log(`Generated ${name}; no database calls were made.`);
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
